import { Router } from 'express';
import rateLimit from 'express-rate-limit';
import * as controller from './auth.controller.js';
import { validate } from '../../middleware/validate.js';
import { authenticate } from '../../middleware/authenticate.js';
import { registerSchema, loginSchema, refreshSchema, tokenSchema, resetPasswordSchema, passwordResetRequestSchema, mfaSetupSchema, mfaCodeSchema } from './auth.validation.js';
import { asyncHandler } from '../../utils/asyncHandler.js';
import env from '../../config/environment.js';
import { createRateLimitStore } from '../../config/redis-rate-limit.js';
const router = Router();
const authLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 10, standardHeaders: 'draft-7', legacyHeaders: false, ...(env.redisUrl ? { store: createRateLimitStore('auth') } : {}) });
router.post('/register', authLimiter, validate(registerSchema), asyncHandler(controller.register));
router.post('/login', authLimiter, validate(loginSchema), asyncHandler(controller.login));
router.post('/verify-email', authLimiter, validate(tokenSchema), asyncHandler(controller.verifyEmail));
router.post('/email-verification/request', authLimiter, validate(passwordResetRequestSchema), asyncHandler(controller.requestEmailVerification));
router.post('/password-reset/request', authLimiter, validate(passwordResetRequestSchema), asyncHandler(controller.requestPasswordReset));
router.post('/password-reset/confirm', authLimiter, validate(resetPasswordSchema), asyncHandler(controller.resetPassword));
router.post('/mfa/setup', authenticate, validate(mfaSetupSchema), asyncHandler(controller.setupMfa));
router.post('/mfa/enable', authenticate, validate(mfaCodeSchema), asyncHandler(controller.enableMfa));
router.post('/refresh', authLimiter, validate(refreshSchema), asyncHandler(controller.refresh));
router.post('/logout', validate(refreshSchema), asyncHandler(controller.logout));
router.get('/me', authenticate, asyncHandler(controller.me));
export default router;
